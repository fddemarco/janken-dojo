"""docs/cli-reference.md, generated from the CLI itself (typer's docs generator).

    uv run python -m janken.cli.reference           # rewrite docs/cli-reference.md
    uv run python -m janken.cli.reference --check   # fail if it is out of date

pre-commit runs the check, so every command and parameter the CLI has is published,
with the help text and the default (from janken.toml) it has.
"""

import html
import os
import sys

import typer
import typer.cli
import typer.main

from .. import settings
from . import app

PATH = os.path.join(settings.ROOT, "docs", "cli-reference.md")
PROGRAM = "uv run janken"


def render() -> str:
    """The reference page, as markdown."""
    command = typer.main.get_command(app)
    ctx = typer.Context(command)
    ctx.ensure_object(dict)
    ctx.obj[typer.cli.MARKUP_MODE_KEY] = app.rich_markup_mode
    docs = typer.cli.get_docs_for_click(
        obj=command, ctx=ctx, name=PROGRAM, title="CLI reference"
    )
    note = (
        "Generated by `uv run python -m janken.cli.reference` from the commands'"
        " own help; don't edit it by hand. Defaults are the values in `janken.toml`"
        " when it was generated (`janken config show` prints the current ones)."
    )
    head, _, body = html.unescape(docs).strip().partition("\n")
    return f"{head}\n\n{note}\n{body}\n"


def is_current() -> bool:
    """Whether docs/cli-reference.md is what `render` gives now."""
    if not os.path.isfile(PATH):
        return False
    with open(PATH, encoding="utf-8") as f:
        return f.read() == render()


def main(argv: list[str]) -> int:
    """Rewrite the reference, or with `--check` only report whether it is current."""
    if "--check" in argv:
        if is_current():
            return 0
        print(
            f"{os.path.relpath(PATH)} is out of date: uv run python -m janken.cli.reference"
        )
        return 1
    with open(PATH, "w", encoding="utf-8") as f:
        f.write(render())
    print(f"wrote {os.path.relpath(PATH)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
