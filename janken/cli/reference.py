"""docs/cli-reference.md, generated from the CLI itself (typer's docs generator).

    uv run python -m janken.cli.reference     # rewrite docs/cli-reference.md

tests/test_cli.py fails when the file is out of date, so every command and parameter
the CLI has is published, with the help text and default it has.
"""

import html
import os

import typer
import typer.cli
import typer.main

from .. import settings
from . import app

PATH = os.path.join(settings.ROOT, "docs", "cli-reference.md")
PROGRAM = "uv run janken"


def render() -> str:
    """The reference page, as markdown."""
    command = typer.main.get_command(app)
    ctx = typer.Context(command)
    ctx.ensure_object(dict)
    ctx.obj[typer.cli.MARKUP_MODE_KEY] = app.rich_markup_mode
    docs = typer.cli.get_docs_for_click(
        obj=command, ctx=ctx, name=PROGRAM, title="CLI reference"
    )
    note = (
        "Generated by `uv run python -m janken.cli.reference` from the commands'"
        " own help; don't edit it by hand. Defaults are the values in `janken.toml`"
        " when it was generated (`janken config show` prints the current ones)."
    )
    head, _, body = html.unescape(docs).strip().partition("\n")
    return f"{head}\n\n{note}\n{body}\n"


if __name__ == "__main__":
    with open(PATH, "w", encoding="utf-8") as f:
        f.write(render())
    print(f"wrote {os.path.relpath(PATH)}")
